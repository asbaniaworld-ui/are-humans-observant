type BlueprintInput = Omit<BlueprintTheme, 'estimatedComplexity'> & { estimatedComplexity?: BlueprintTheme['estimatedComplexity'] };

function defineBlueprint(entry: BlueprintInput): BlueprintTheme {
  return {
    ...entry,
    estimatedComplexity: entry.estimatedComplexity ?? entry.difficultyTier,
    assignmentPriority: entry.assignmentPriority ?? (CANONICAL_CAMPAIGN_IDS.has(entry.id) ? 100 : 0),
  };
}

